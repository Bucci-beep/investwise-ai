def normalise(text: str) -> str:
    return re.sub(r"[^\w]+", " ", text.casefold()).strip()


def build_rows(specification: dict) -> list[dict[str, str | None]]:
    options = {o["id"]: q["id"] for q in specification["questions"] for o in q["main_options"]}
    if set(options) != set(POSITIVE):
        raise ValueError(f"option mismatch: missing={set(options) - set(POSITIVE)} extra={set(POSITIVE) - set(options)}")
    if set(NEGATIVE) != set(specification["question_order"]):
        raise ValueError("negative examples must cover every question")
    rows = []
    counts = Counter()

    def append(question_id, text, bucket, option_id, split, family):
        counts[(question_id, split)] += 1
        rows.append({
            "id": f"SYNTH-V1-{question_id}-{split.upper()}-{counts[(question_id, split)]:03d}",
            "question_id": question_id, "text": text, "bucket": bucket,
            "option_id": option_id, "source": SOURCE,
            "group_id": f"{question_id}:{split}:{family}", "split": split,
        })

    for option_id, split_texts in POSITIVE.items():
        if tuple(map(len, split_texts)) != (6, 5, 2):
            raise ValueError(f"unexpected positive count for {option_id}")
        for split, texts, family in zip(("train", "calibration", "test"), split_texts,
                                      ("direct", "situational", "correction_boundary")):
            for utterance in texts:
                append(options[option_id], utterance, "clarity", option_id, split, f"{option_id}:{family}")
    for question_id, by_split in NEGATIVE.items():
        for split, bucket_texts in by_split.items():
            expected = 10 if split == "calibration" else 4 if split == "train" else 2
            for bucket, texts in zip(("undecided", "confusion"), bucket_texts):
                if len(texts) != expected:
                    raise ValueError(f"unexpected negative count for {question_id}/{split}/{bucket}")
                for utterance in texts:
                    append(question_id, utterance, bucket, None, split, f"{bucket}:authored_contrasts")
    return rows


def validate(rows: list[dict], specification: dict) -> dict:
    ids = set()
    text_keys = {}
    group_splits = defaultdict(set)
    option_ids = {q["id"]: {o["id"] for o in q["main_options"]} for q in specification["questions"]}
    counts = defaultdict(lambda: {"rows": 0, "buckets": Counter(), "options": Counter()})
    for row in rows:
        if tuple(row) != FIELDS or row["id"] in ids or not row["text"].strip():
            raise ValueError(f"invalid row {row}")
        ids.add(row["id"])
        if row["question_id"] not in option_ids or row["bucket"] not in {"clarity", "undecided", "confusion"}:
            raise ValueError(f"invalid label {row}")
        if row["split"] not in {"train", "calibration", "test"} or row["source"] != SOURCE:
            raise ValueError(f"invalid provenance {row}")
        if row["bucket"] == "clarity":
            if row["option_id"] not in option_ids[row["question_id"]]:
                raise ValueError(f"unsupported option {row}")
        elif row["option_id"] is not None:
            raise ValueError(f"non-clarity option must be null {row}")
        key = (row["question_id"], normalise(row["text"]))
        if key in text_keys:
            raise ValueError(f"normalized duplicate: {text_keys[key]} and {row['id']}")
        text_keys[key] = row["id"]
        group_splits[row["group_id"]].add(row["split"])
        count = counts[(row["split"], row["question_id"])]
        count["rows"] += 1
        count["buckets"][row["bucket"]] += 1
        if row["option_id"] is not None:
            count["options"][row["option_id"]] += 1
    if any(len(splits) != 1 for splits in group_splits.values()):
        raise ValueError("semantic family crossed splits")
    by_split = {}
    for split in ("train", "calibration", "test"):
        by_split[split] = {"rows": 0, "buckets": Counter(), "questions": {}}
        for question_id in specification["question_order"]:
            count = counts[(split, question_id)]
            if set(count["buckets"]) != {"clarity", "undecided", "confusion"} or set(count["options"]) != option_ids[question_id]:
                raise ValueError(f"incomplete labels for {split}/{question_id}")
            by_split[split]["rows"] += count["rows"]
            by_split[split]["buckets"].update(count["buckets"])
            by_split[split]["questions"][question_id] = count
    return {
        "schema_valid": True, "all_questions_covered_each_split": True,
        "all_options_covered_each_split": True, "question_count": len(option_ids),
        "option_count": sum(map(len, option_ids.values())), "total_rows": len(rows),
        "within_question_normalized_duplicates": 0, "cross_split_group_overlap": 0,
        "counts": by_split,
    }


